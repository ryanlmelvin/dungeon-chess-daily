// Each hand-drawn 16-pixel silhouette sits inside a 20-pixel texture.
// The transparent border keeps neighboring tiles and point sampling clean.
function framed(rows) {
  if (rows.length !== 16 || rows.some((row) => row.length > 16)) {
    throw new Error('A sprite must have sixteen rows of at most sixteen pixels.');
  }
  const empty = '.'.repeat(SPRITE_SIZE);
  return Object.freeze([empty, empty, ...rows.map((row) => `..${row.padEnd(16, '.')}..`), empty, empty]);
}

