function monsterPalette(name, adjective, shade, body, light, glow) {
  return Object.freeze({ name, adjective, colors: Object.freeze({
    d: shade, s: body, b: light, w: glow, r: body, h: light,
    p: shade, l: body, a: body, t: light, o: body, y: light, e: '#fff7e6',
  }) });
}

