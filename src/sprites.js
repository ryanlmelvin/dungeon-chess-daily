/** Draw at integer scale for crisp newspaper thumbnails and Three.js textures. */
export function drawSprite(ctx, id, x = 0, y = 0, scale = 1, paletteOverride = {}) {
  const sprite = SPRITES[id];
  if (!sprite) return false;
  const palette = { ...PALETTE, ...paletteOverride };
  for (let row = 0; row < sprite.length; row++) {
    for (let column = 0; column < sprite[row].length; column++) {
      const color = palette[sprite[row][column]];
      if (!color) continue;
      ctx.fillStyle = color;
      ctx.fillRect(x + column * scale, y + row * scale, scale, scale);
    }
  }
  return true;
}
