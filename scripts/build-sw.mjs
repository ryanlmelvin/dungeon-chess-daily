import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve('dist');
async function walk(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await walk(path));
    else result.push(path);
  }
  return result;
}
// Optional music is cached on first play instead, so players who never turn it on never download it.
const isMusic = (file) => relative(root, file).split('\\').join('/').startsWith('music/');
const files = (await walk(root)).filter((file) => !['sw.js', 'release.json'].includes(relative(root, file)) && !isMusic(file)).sort();
const fingerprint = createHash('sha256');
fingerprint.update(await readFile(fileURLToPath(import.meta.url)));
const resources = [];
for (const file of files) {
  const content = await readFile(file);
  const name = relative(root, file).split('\\').join('/');
  fingerprint.update(name).update(content);
  resources.push({ url: name, integrity: `sha256-${createHash('sha256').update(content).digest('base64')}` });
}
const version = fingerprint.digest('hex').slice(0, 12);
const release = JSON.stringify({ version }) + '\n';
await writeFile(join(root, 'release.json'), release);
resources.push({ url: 'release.json', integrity: `sha256-${createHash('sha256').update(release).digest('base64')}` });
const worker = `// Dungeon Chess Daily ${version}. Generated by scripts/build-sw.mjs.
const VERSION = ${JSON.stringify(version)};
const RESOURCES = ${JSON.stringify(resources)};
const SCOPE = new URL(self.registration.scope);
const PREFIX = 'dungeon-chess-daily:' + SCOPE.pathname + ':';
const CACHE = PREFIX + VERSION;
// Music files are never renamed in place, so one cache serves every release.
const MUSIC_CACHE = PREFIX + 'music';
const canonical = (path) => new URL(path, SCOPE).href;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    try {
      // Integrity prevents a partially deployed release becoming an offline shell.
      await Promise.all(RESOURCES.map(async ({ url, integrity }) => {
        const request = new Request(canonical(url), { cache: 'reload', integrity });
        const response = await fetch(request);
        if (!response.ok) throw new Error('Missing offline asset: ' + url);
        await cache.put(canonical(url), response);
      }));
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
    // First install activates naturally. An existing installation waits for consent.
  })());
});

self.addEventListener('activate', (event) => {
  // Previous immutable bundles stay available for tabs that have not chosen to reload.
  // Neither this app's saved progress nor another project's caches are removed.
  event.waitUntil(self.clients.claim());
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
  if (event.data?.type === 'GET_VERSION') event.ports[0]?.postMessage({ version: VERSION });
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  const path = url.pathname.slice(SCOPE.pathname.length);
  if (path === 'sw.js') return;
  if (path === 'update.html') {
    // Recovery always reaches the network when possible, independent of the app shell.
    event.respondWith(fetch(new Request(request, { cache: 'no-store' })).catch(async () => {
      const cache = await caches.open(CACHE);
      return await cache.match(canonical('update.html')) || Response.error();
    }));
    return;
  }
  if (path.startsWith('music/')) {
    event.respondWith((async () => {
      const cache = await caches.open(MUSIC_CACHE);
      const cached = await cache.match(canonical(path));
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok && response.status === 200) await cache.put(canonical(path), response.clone());
      // Hold the last few soundtracks offline without growing to the whole library.
      const stored = await cache.keys();
      for (const old of stored.slice(0, Math.max(0, stored.length - 9))) await cache.delete(old);
      return response;
    })());
    return;
  }
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const key = request.mode === 'navigate' ? canonical('index.html') : canonical(path);
    const cached = await cache.match(key);
    if (cached) return cached;
    // Only immutable build assets may come from an older release.
    if (path.startsWith('assets/')) {
      for (const name of await caches.keys()) {
        if (!name.startsWith(PREFIX) || name === CACHE) continue;
        const previous = await (await caches.open(name)).match(key);
        if (previous) return previous;
      }
    }
    return fetch(request);
  })());
});
`;
await writeFile(join(root, 'sw.js'), worker);
console.log(`Offline release ${version}: ${resources.length} assets`);
