// Build src/mate-arenas.js, the arenas a mate floor is composed in
// (src/composer.js composeMate), from the lichess puzzle database
// (database.lichess.org, CC0): lichess_db_puzzle.csv.zst, about 310 MB, which
// is not in the repo. Run by hand when the library should change; needs the
// `zstd` command.
//   node scripts/build-mate-arenas.mjs path/to/lichess_db_puzzle.csv.zst [--per-piece N] [--plays N] [--walls N]
// An arena is a mate in one to three in which the solver has only a king and
// one piece: the squares of that piece, its king and the enemy king once the
// opponent's first move is played, and every other enemy man as a wall. A
// puzzle black solves is flipped, so the solver plays up the board. Kept: the
// puzzles played at least --plays times (100) with at most --walls other men
// (6), one per distinct arena, the most played first, --per-piece of each
// piece (300).
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { writeFile } from 'node:fs/promises';
import { ALPHABET } from '../src/route-code.js';

const input = process.argv[2];
if (!input) throw new Error('Usage: node scripts/build-mate-arenas.mjs path/to/lichess_db_puzzle.csv.zst');
const arg = (name, fallback) => { const at = process.argv.indexOf(`--${name}`); return at > 0 ? Number(process.argv[at + 1]) : fallback; };
const perPiece = arg('per-piece', 300), minPlays = arg('plays', 100), maxWalls = arg('walls', 6);
const PIECES = { r: 'rook', q: 'queen', n: 'knight', b: 'bishop' };
const files = 'abcdefgh';
const square = (name) => ({ x: files.indexOf(name[0]), y: 8 - Number(name[1]) });

function board(fen) {
  const grid = Array.from({ length: 8 }, () => Array(8).fill(null));
  fen.split(' ')[0].split('/').forEach((row, y) => { let x = 0; for (const ch of row) { if (/\d/.test(ch)) x += Number(ch); else grid[y][x++] = ch; } });
  return grid;
}
// Play a move in lichess's notation (e2e4, e7e8q) on the board: enough chess for a puzzle's first move.
function apply(grid, uci) {
  const from = square(uci.slice(0, 2)), to = square(uci.slice(2, 4)), man = grid[from.y][from.x];
  if (!man) throw new Error('No man on the move\'s square.');
  if (man.toLowerCase() === 'p' && from.x !== to.x && !grid[to.y][to.x]) grid[from.y][to.x] = null;
  if (man.toLowerCase() === 'k' && Math.abs(to.x - from.x) === 2) {
    const rookFrom = to.x > from.x ? 7 : 0, rookTo = to.x > from.x ? 5 : 3;
    grid[from.y][rookTo] = grid[from.y][rookFrom]; grid[from.y][rookFrom] = null;
  }
  grid[to.y][to.x] = uci[4] ? (man === man.toUpperCase() ? uci[4].toUpperCase() : uci[4]) : man;
  grid[from.y][from.x] = null;
}

const found = Object.fromEntries(Object.values(PIECES).map((piece) => [piece, []]));
const zstd = spawn('zstd', ['-dc', input], { stdio: ['ignore', 'pipe', 'inherit'] });
let rows = 0;
for await (const line of createInterface({ input: zstd.stdout })) {
  if (!rows++) continue;
  const [, fen, moves, , , , plays, themes] = line.split(',');
  if (!/\bmateIn[123]\b/.test(themes) || Number(plays) < minPlays) continue;
  try {
    const grid = board(fen);
    apply(grid, moves.split(' ')[0]);
    // The solver moves second: it is the side not to move in the puzzle's position.
    const white = fen.split(' ')[1] === 'b';
    const mine = [], theirs = [];
    for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) {
      const man = grid[y][x];
      if (man) ((man === man.toUpperCase()) === white ? mine : theirs).push({ man: man.toLowerCase(), x, y: white ? y : 7 - y });
    }
    const piece = mine.find((unit) => unit.man !== 'k'), king = mine.find((unit) => unit.man === 'k'), foe = theirs.find((unit) => unit.man === 'k');
    if (mine.length !== 2 || !piece || !king || !foe || !PIECES[piece.man] || theirs.length - 1 > maxWalls) continue;
    const code = (tile) => ALPHABET[tile.y * 8 + tile.x];
    const walls = theirs.filter((unit) => unit.man !== 'k').map(code).sort().join('');
    found[PIECES[piece.man]].push({ arena: `${code(piece)}${code(king)}${code(foe)}${walls}`, plays: Number(plays) });
  } catch { /* a row this reader can't play is left out */ }
}
const table = {};
for (const [piece, list] of Object.entries(found)) {
  const seen = new Set();
  table[piece] = list.sort((a, b) => b.plays - a.plays || (a.arena < b.arena ? -1 : 1)).filter(({ arena }) => !seen.has(arena) && seen.add(arena)).slice(0, perPiece).map(({ arena }) => arena);
}
const source = '// SPDX-License-Identifier: GPL-3.0-only\n'
  + '// Generated by scripts/build-mate-arenas.mjs from the lichess puzzle database (database.lichess.org, CC0):\n'
  + '// mates in one to three in which the solver has only a king and one piece. Each arena is a string of squares\n'
  + '// (src/route-code.js ALPHABET): the piece, its king, the enemy king, then a wall for every other enemy man.\n'
  + '// The composer alone reads it (src/composer.js composeMate); the app never carries it.\n'
  + `export const MATE_ARENAS = Object.freeze(${JSON.stringify(table)});\n`;
await writeFile(new URL('../src/mate-arenas.js', import.meta.url), source);
console.log(`Read ${rows - 1} puzzles; wrote ${Object.entries(table).map(([piece, list]) => `${list.length} ${piece}`).join(', ')} arenas.`);
